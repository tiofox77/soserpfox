 * Traduções do menu lateral e do painel de facturação.
 *
 * Notas de tradução que não são óbvias e que se perdem se não ficarem escritas:
 *
 *   · Recibos ≠ Recebimentos. O primeiro é o documento (Receipt / Reçu), o
 *     segundo é dinheiro que entrou (Amounts Received / Encaissements). Em
