 *     eles emitem aos clientes deles. Em francês os dois dariam "Facturation",
 *     por isso o de cima ficou "Abonnements".
 *
 *   · Tenants em francês não é "Locataires" — isso são inquilinos de casas.
 *     Ficou "Entreprises", que é o que são.
 *
 *   · Hóspedes ficou "Hôtes" e não "Clients": no hotel já há Clientes, e ter
 *     as duas coisas com o mesmo nome no mesmo menu não ajudava ninguém.
 *
 * Uso:  php scripts/lote3_menu_traducoes.php
 */

