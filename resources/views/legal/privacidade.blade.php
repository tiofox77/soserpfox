<p>
    Esta Política explica como a <strong>Softec Angola</strong> trata dados pessoais no âmbito do
    <strong>SOSERP</strong>, em conformidade com a <strong>Lei n.º 22/11, de 17 de Junho — Lei de
    Protecção de Dados Pessoais</strong> de Angola e demais legislação aplicável.
</p>

<h2>1. Dois papéis diferentes — e porque importa</h2>
<p>
    O SOSERP trata dados pessoais em duas qualidades distintas. A diferença determina quem decide
    sobre esses dados:
</p>
<ul>
    <li>
        <strong>Como responsáveis pelo tratamento</strong> — relativamente aos dados da
        <strong>conta do cliente</strong>: nome e email de quem se regista, dados da empresa
        subscritora, facturação da subscrição e registos de acesso ao serviço.
    </li>
    <li>
        <strong>Como subcontratantes</strong> — relativamente aos <strong>dados que o cliente
        introduz</strong> no sistema (os seus próprios clientes, fornecedores, trabalhadores,
        pacientes, hóspedes). Esses dados são do cliente; nós apenas os alojamos e processamos por
        conta e segundo instruções dele. <strong>O cliente é o responsável pelo tratamento</strong>
        e deve assegurar que tem fundamento legal para os recolher.
    </li>
</ul>

<h2>2. Que dados recolhemos</h2>

<h3>2.1 Dados de conta e subscrição</h3>
<ul>
    <li>Identificação: nome, email, telefone, cargo;</li>
    <li>Empresa: designação, NIF, morada, contactos;</li>
    <li>Subscrição: plano, facturas emitidas, pagamentos e comprovativos.</li>
</ul>

<h3>2.2 Dados técnicos e de utilização</h3>
<ul>
    <li>Registos de acesso (data/hora, endereço IP, entradas e saídas, tentativas falhadas);</li>
    <li>Trilha de auditoria de operações relevantes no sistema (quem fez o quê e quando);</li>
    <li>Registos de erros, para diagnóstico e correcção;</li>
    <li>Na versão local: identificador do equipamento, versão instalada e data do último contacto,
        para validação da licença.</li>
</ul>

<h3>2.3 Dados introduzidos pelo cliente</h3>
<p>
    Os que o cliente decidir registar no exercício da sua actividade — por exemplo dados de clientes
    e fornecedores, documentos de venda e compra, stock, e dados de trabalhadores no módulo de
    recursos humanos. <strong>Não usamos estes dados para fins próprios.</strong>
</p>

<h2>3. Para que usamos os dados e com que fundamento</h2>
<ul>
    <li><strong>Prestar o serviço</strong> — execução do contrato;</li>
    <li><strong>Facturar e cobrar</strong> a subscrição — execução do contrato e obrigação legal;</li>
    <li><strong>Cumprir obrigações fiscais</strong>, incluindo a comunicação de documentos à AGT —
        obrigação legal;</li>
    <li><strong>Suporte técnico</strong> e resposta a pedidos — execução do contrato;</li>
    <li><strong>Segurança</strong>: detecção de acessos indevidos, auditoria e integridade —
        interesse legítimo em proteger o serviço e os dados nele contidos;</li>
    <li><strong>Avisos sobre a subscrição</strong> (factura emitida, a vencer, período a terminar) —
        execução do contrato;</li>
    <li><strong>Comunicações comerciais</strong>, quando existam — apenas com consentimento, sempre
        com possibilidade de cancelamento.</li>
</ul>
<p><strong>Não vendemos dados pessoais.</strong></p>

<h2>4. Com quem partilhamos</h2>
<p>Partilhamos apenas o necessário, com:</p>
<ul>
    <li><strong>Administração Geral Tributária (AGT)</strong> — os elementos dos documentos fiscais,
        por imposição legal;</li>
    <li><strong>Fornecedores de infra-estrutura</strong> (alojamento e cópias de segurança);</li>
    <li><strong>Fornecedores de comunicações</strong> (envio de email e SMS), que recebem apenas o
        destinatário e a mensagem;</li>
    <li><strong>Autoridades públicas</strong>, quando legalmente exigido.</li>
</ul>
<p>
    Estes fornecedores actuam por nossa conta, vinculados a obrigações de confidencialidade e
    segurança.
</p>

<h2>5. Onde ficam os dados</h2>
<p>
    Na versão em <strong>nuvem</strong>, os dados são alojados em servidores dos nossos fornecedores
    de infra-estrutura, podendo situar-se fora de Angola. Nesse caso, adoptamos as garantias exigidas
    pela legislação aplicável às transferências internacionais.
</p>
<p>
    Na versão <strong>local</strong>, os dados ficam <strong>no equipamento do cliente</strong> e não
    nos são transmitidos, com excepção de informação mínima de licenciamento (identificador do
    equipamento, versão e data de contacto).
</p>

<h2>6. Durante quanto tempo</h2>
<ul>
    <li><strong>Dados de conta:</strong> enquanto a subscrição vigorar e pelo período necessário
        após a cessação, para efeitos de prova e obrigações legais;</li>
    <li><strong>Documentos fiscais e contabilísticos:</strong> pelos prazos de conservação impostos
        pela legislação fiscal angolana;</li>
    <li><strong>Registos de acesso e auditoria:</strong> pelo período necessário aos fins de
        segurança que os justificam;</li>
    <li><strong>Dados introduzidos pelo cliente:</strong> enquanto o cliente os mantiver ou até
        instrução de eliminação, salvo obrigação legal de conservação.</li>
</ul>

<h2>7. Segurança</h2>
<p>Entre as medidas aplicadas contam-se:</p>
<ul>
    <li>Ligações cifradas (HTTPS) e cabeçalhos de segurança;</li>
    <li>Palavras-passe guardadas com algoritmos de <em>hash</em> — <strong>nunca em texto
        legível</strong>;</li>
    <li>Separação lógica dos dados de cada empresa e controlo de acessos por perfis e permissões;</li>
    <li>Trilha de auditoria que não permite reescrita silenciosa;</li>
    <li>Cópias de segurança periódicas na nuvem;</li>
    <li>Na versão local, verificação de integridade dos ficheiros do programa.</li>
</ul>
<p>
    Nenhum sistema é totalmente inviolável. Em caso de violação de dados com risco relevante,
    informaremos os afectados e as autoridades competentes nos termos da lei.
</p>

<h2>8. Direitos do titular dos dados</h2>
<p>Nos termos da Lei n.º 22/11, o titular tem direito a:</p>
<ul>
    <li><strong>Aceder</strong> aos seus dados e saber como são tratados;</li>
    <li><strong>Rectificar</strong> dados incorrectos ou incompletos;</li>
    <li><strong>Apagar</strong> ou <strong>bloquear</strong> dados, quando aplicável;</li>
    <li><strong>Opor-se</strong> a determinados tratamentos;</li>
    <li><strong>Retirar o consentimento</strong>, quando o tratamento nele se baseie;</li>
    <li><strong>Reclamar</strong> junto da <strong>Agência de Protecção de Dados (APD)</strong>.</li>
</ul>
<p>
    <strong>Nota importante:</strong> se os seus dados estiverem no SOSERP porque uma empresa nossa
    cliente os registou (por exemplo, é cliente ou trabalhador dessa empresa), o pedido deve ser
    dirigido <strong>a essa empresa</strong>, que é a responsável pelo tratamento. Se nos for
    dirigido, encaminhamo-lo.
</p>

<h2>9. Cookies</h2>
<p>
    Utilizamos cookies <strong>estritamente necessários</strong> ao funcionamento — manter a sessão
    iniciada e proteger formulários contra fraude (CSRF). Sem eles o sistema não funciona.
</p>
<p>
    Podemos utilizar cookies ou registos de <strong>estatísticas de utilização</strong> agregadas
    para perceber o desempenho do site. Pode bloquear cookies no navegador, mas nesse caso poderá
    não conseguir iniciar sessão.
</p>

<h2>10. Menores</h2>
<p>
    O SOSERP destina-se a utilização profissional e não é dirigido a menores. Não recolhemos
    conscientemente dados de menores para contas de utilizador.
</p>

